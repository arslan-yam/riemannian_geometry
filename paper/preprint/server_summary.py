"""Summaries of the cluster results (results/server) for the paper: one markdown file with every table we use.

  python3 paper/preprint/server_summary.py [results/server] > notes/server_results.md
"""
import glob, json, os, sys

R = sys.argv[1] if len(sys.argv) > 1 else "results/server"
TERR = ["TJ", "SC", "VS", "AU", "GI", "LH"]
SIZES = [500000, 1002528, 1503378, 2000000, 2504322]


def J(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def var(d, variant="dense/sym", s="random"):
    for v in d["variants"]:
        if v["variant"] == variant and v["set"] == s:
            return v
    return None


def allsound(d):
    return all(v["sound"] for v in d["variants"]), sum(v["pairs"] for v in d["variants"] if v["variant"] == d["variants"][0]["variant"])


def mb(b):
    return b / 1e6


def h(s):
    return s / 3600


def pct(x):
    return 100 * x


def row(*c):
    print("| " + " | ".join(str(x) for x in c) + " |")


def ours_line(d, variant):
    v = var(d, variant); a = var(d, variant, "a2a")
    ok, npairs = allsound(d)
    return (f"{h(d['build_s']):.1f} h", f"{mb(v['index_bytes']):,.0f} MB", f"{v['query_us']:.2f} us",
            f"{pct(v['est_mean']):.4f}%", f"{pct(v['est_max']):.3f}%", f"{pct(v['max_ub_err']):.2f}%",
            f"{a['query_us']:.0f} us / {pct(a['est_mean']):.3f}%" if a else "", "yes" if ok else "NO", f"{d['peak_rss_mb'] / 1e3:.1f} GB")


print("# Cluster results (generated by paper/preprint/server_summary.py)\n")
print("## Ours at 500k faces (six terrains), V2V random pairs; A2A column: query / mean error; sound over all sets\n")
row("terrain", "variant", "build", "size", "query", "mean err", "max err", "max UB err", "A2A", "sound", "peak RSS")
row(*["---"] * 11)
for t in TERR:
    for tag, var_ in (("kd", "dense/sym"), ("kd", "code8/sym"), ("k64", "dense/sym"), ("k64", "code8/sym"), ("e01", "dense/sym"), ("e01", "code8/sym")):
        d = J(f"ours.{t}.{tag}.json")
        if d and var(d, var_):
            row(t, f"{tag} {var_}", *ours_line(d, var_))

